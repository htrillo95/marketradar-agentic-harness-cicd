#!/usr/bin/env python3
"""
Run an advisory agentic code review on changed files.

The review is performed by the `marketradar-code-reviewer` Claude Code
subagent, run non-interactively as

    claude -p <prompt> --agent marketradar-code-reviewer \
        --mcp-config <tmp>/mcp-config.json --strict-mcp-config ...

This script:
- Reads CHANGED_FILES from the environment.
- Reads ANTHROPIC_API_KEY from the environment (used only by the claude CLI;
  it is never written to any output).
- Selects only text-like changed files and lists their paths in the prompt;
  the subagent reads them itself with Read/Grep/Glob.
- Registers only the retrieval MCP server (AGENT_ROLE=reviewer) via
  --strict-mcp-config, so no other MCP server (for example Slack or Gmail
  from the user-level settings) is loaded. The server's audit log is written
  to /out/mcp-audit/retrieval-audit-log.jsonl and exists only if the agent
  actually called the retrieval tool.
- Denies Bash, Edit, Write, NotebookEdit, WebFetch and WebSearch.
- Writes /out/review-output.md.
- Writes /out/review-audit.json.
- Always exits 0 because this review is advisory.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import textwrap
from datetime import datetime, timezone
from pathlib import Path

OUT_DIR = Path("/out")
MAX_FILE_CHARS = 20_000
MAX_TOTAL_CHARS = 60_000

REVIEWER_AGENT = "marketradar-code-reviewer"
REVIEWER_MECHANISM = f"claude -p --agent {REVIEWER_AGENT}"
REVIEWER_TIMEOUT_SECONDS = 600
REVIEWER_MAX_TURNS = "20"
ALLOWED_TOOLS = "Read,Grep,Glob,mcp__retrieval__retrieve"
DISALLOWED_TOOLS = "Bash,Edit,Write,NotebookEdit,WebFetch,WebSearch"
MCP_SERVER_SCRIPT = "/workspace/mcp-servers/retrieval/server.py"
MCP_AGENT_ROLE = "reviewer"
MCP_AUDIT_RELATIVE = "mcp-audit/retrieval-audit-log.jsonl"
STDERR_TAIL_CHARS = 500

REVIEW_HEADER = (
    f"> Generated by the `{REVIEWER_AGENT}` Claude Code subagent. "
    "Advisory only: this review does not block merge."
)
NOT_RUN_HEADER = (
    f"> Advisory review job: the `{REVIEWER_AGENT}` Claude Code subagent did not produce a review. "
    "Advisory only: this does not block merge."
)

TEXT_EXTENSIONS = {
    ".py", ".js", ".ts", ".tsx", ".jsx", ".json", ".yaml", ".yml",
    ".md", ".txt", ".sh", ".toml", ".ini", ".cfg", ".html", ".css",
}


def run(cmd: list[str]) -> str:
    return subprocess.check_output(cmd, text=True, stderr=subprocess.DEVNULL).strip()


def is_text_candidate(path: Path) -> bool:
    if path.name in {"Dockerfile", "Makefile"}:
        return True
    return path.suffix.lower() in TEXT_EXTENSIONS


def read_changed_files() -> list[str]:
    raw = os.environ.get("CHANGED_FILES", "").strip()
    if raw:
        return [p for p in raw.split() if p]

    # Fallback for local debugging.
    try:
        return run(["git", "diff", "--name-only", "HEAD~1", "HEAD"]).splitlines()
    except Exception:
        return []


def collect_file_context(paths: list[str]) -> tuple[str, list[dict]]:
    chunks: list[str] = []
    audit_files: list[dict] = []
    total = 0

    for name in paths:
        path = Path(name)

        record = {
            "path": name,
            "included": False,
            "reason": "",
            "chars": 0,
        }

        if not path.exists() or not path.is_file():
            record["reason"] = "missing_or_not_file"
            audit_files.append(record)
            continue

        if not is_text_candidate(path):
            record["reason"] = "skipped_non_text_extension"
            audit_files.append(record)
            continue

        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except Exception as exc:
            record["reason"] = f"read_error: {exc}"
            audit_files.append(record)
            continue

        if not text.strip():
            record["reason"] = "empty_file"
            audit_files.append(record)
            continue

        if len(text) > MAX_FILE_CHARS:
            text = text[:MAX_FILE_CHARS] + "\n\n[TRUNCATED]\n"

        if total + len(text) > MAX_TOTAL_CHARS:
            record["reason"] = "skipped_total_context_limit"
            audit_files.append(record)
            continue

        chunks.append(f"\n\n--- FILE: {name} ---\n{text}")
        total += len(text)

        record["included"] = True
        record["reason"] = "included"
        record["chars"] = len(text)
        audit_files.append(record)

    return "\n".join(chunks), audit_files


def _api_key() -> str:
    return os.environ.get("ANTHROPIC_API_KEY", "").strip()


def _redact(text: str) -> str:
    """Remove the API key value from any text that may reach an output file."""
    key = _api_key()
    if key and text:
        return text.replace(key, "[REDACTED]")
    return text


def mcp_audit_log_path() -> Path:
    # Computed from OUT_DIR at call time so tests can monkeypatch OUT_DIR.
    return OUT_DIR / MCP_AUDIT_RELATIVE


def build_prompt(files: list[str]) -> str:
    file_list = "\n".join(f"- {name}" for name in files)
    return textwrap.dedent(
        """
        This is an advisory CI review of a pull request. It does not block merge.

        The changed files to review are listed below. Paths are relative to the
        repository root, which is /workspace (the current working directory):

        {file_list}

        Read these files yourself and follow your own review instructions.
        Report at most 5 findings. For each finding give: severity, file, what
        the issue is, why it matters, and a suggested fix. Do not invent issues;
        if there are no meaningful findings, say so clearly.

        Return the review as Markdown starting with the heading
        `## Advisory Code Review`.
        """
    ).strip().format(file_list=file_list)


def _not_run_result(review: str, error: str | None, exit_code: int | None = None,
                    invoked: bool = False) -> dict:
    return {
        "review": review,
        "ran": False,
        "invoked": invoked,
        "exit_code": exit_code,
        "is_error": None,
        "num_turns": None,
        "total_cost_usd": None,
        "subtype": None,
        "error": error,
    }


def run_reviewer_subagent(files: list[str]) -> dict:
    if not _api_key():
        return _not_run_result(
            "## Advisory Code Review\n\n"
            "No review was performed because `ANTHROPIC_API_KEY` was not available. "
            "Confirm that the repository secret is configured and injected only into this step.\n",
            error="anthropic_api_key_unavailable",
        )

    audit_log = mcp_audit_log_path()
    audit_log.parent.mkdir(parents=True, exist_ok=True)

    config_dir = Path(tempfile.mkdtemp(prefix="reviewer-mcp-"))
    config_path = config_dir / "mcp-config.json"
    config = {
        "mcpServers": {
            "retrieval": {
                "command": "python",
                "args": [MCP_SERVER_SCRIPT],
                "env": {
                    "AGENT_ROLE": MCP_AGENT_ROLE,
                    "RETRIEVAL_AUDIT_LOG": str(audit_log),
                },
            }
        }
    }
    try:
        config_path.write_text(json.dumps(config, indent=2), encoding="utf-8")
    except Exception:
        shutil.rmtree(config_dir, ignore_errors=True)
        raise

    cmd = [
        "claude", "-p", build_prompt(files),
        "--agent", REVIEWER_AGENT,
        "--mcp-config", str(config_path),
        "--strict-mcp-config",
        "--allowedTools", ALLOWED_TOOLS,
        "--disallowedTools", DISALLOWED_TOOLS,
        "--output-format", "json",
        "--max-turns", REVIEWER_MAX_TURNS,
    ]
    model = os.environ.get("ANTHROPIC_MODEL", "").strip()
    if model:
        cmd += ["--model", model]

    try:
        return _invoke_claude(cmd)
    finally:
        # The audit log lives under OUT_DIR, so removing the config dir does not affect it.
        shutil.rmtree(config_dir, ignore_errors=True)


def _invoke_claude(cmd: list[str]) -> dict:
    def failed(detail: str, error: str, exit_code: int | None = None, stderr: str = "",
               started: bool = True) -> dict:
        text = (
            "## Advisory Code Review\n\n"
            f"The reviewer subagent did not complete ({detail}). No review was produced.\n"
        )
        tail = _redact((stderr or "")[-STDERR_TAIL_CHARS:]).strip()
        if tail:
            text += f"\nLast lines of stderr:\n\n```text\n{tail}\n```\n"
        return _not_run_result(text, error=error, exit_code=exit_code, invoked=started)

    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=REVIEWER_TIMEOUT_SECONDS)
    except subprocess.TimeoutExpired:
        return failed(f"timed out after {REVIEWER_TIMEOUT_SECONDS} seconds", "TimeoutExpired")
    except FileNotFoundError:
        # The claude process never started, so no MCP server was started either.
        return failed("the `claude` CLI was not found", "FileNotFoundError", started=False)

    if proc.returncode != 0:
        return failed(
            f"exit code {proc.returncode}", f"exit_code_{proc.returncode}",
            exit_code=proc.returncode, stderr=proc.stderr,
        )

    try:
        data = json.loads(proc.stdout)
        if not isinstance(data, dict):
            raise ValueError("output is not a JSON object")
    except (json.JSONDecodeError, ValueError) as exc:
        return failed(
            f"could not parse JSON output: {type(exc).__name__}", type(exc).__name__,
            exit_code=proc.returncode, stderr=proc.stderr,
        )

    metrics = {
        "is_error": data.get("is_error"),
        "num_turns": data.get("num_turns"),
        "total_cost_usd": data.get("total_cost_usd"),
        "subtype": data.get("subtype"),
    }
    result_text = str(data.get("result") or "").strip()
    subtype = metrics["subtype"]

    reason = None
    if metrics["is_error"] is True:
        reason = str(subtype) if subtype else "is_error"
    elif subtype is not None and subtype != "success":
        reason = str(subtype)
    elif not result_text:
        reason = "empty_result"

    if reason is not None:
        text = (
            "## Advisory Code Review\n\n"
            f"The reviewer subagent reported an error (`{reason}`) and did not produce a review.\n"
        )
        diagnostic = _redact(result_text[:STDERR_TAIL_CHARS]).strip()
        if diagnostic:
            quoted = "\n".join(f"> {line}" for line in diagnostic.splitlines())
            text += f"\nDiagnostic output (truncated):\n\n{quoted}\n"
        result = _not_run_result(
            text, error=f"claude_reported_error: {reason}", exit_code=proc.returncode, invoked=True,
        )
        result.update(metrics)
        return result

    return {
        "review": result_text,
        "ran": True,
        "invoked": True,
        "exit_code": proc.returncode,
        **metrics,
        "error": None,
    }


def mcp_audit_summary(invoked: bool) -> dict:
    """Describe the MCP audit log from the file actually on disk."""
    path = mcp_audit_log_path()
    present = path.is_file()
    records = 0
    if present:
        try:
            records = sum(
                1 for line in path.read_text(encoding="utf-8", errors="replace").splitlines() if line.strip()
            )
        except Exception:
            records = 0
    return {
        "servers_configured": ["retrieval"] if invoked else [],
        "agent_role": MCP_AGENT_ROLE,
        "audit_log": MCP_AUDIT_RELATIVE if present else None,
        "audit_log_present": present,
        "audit_log_records": records,
    }


def _run() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    changed_files = read_changed_files()
    file_context, audit_files = collect_file_context(changed_files)
    included = [record["path"] for record in audit_files if record["included"]]

    if not file_context.strip() or not included:
        result = _not_run_result(
            "## Advisory Code Review\n\n"
            "No reviewable text files were found in this change.\n",
            error="no_reviewable_files",
        )
    else:
        result = run_reviewer_subagent(included)

    header = REVIEW_HEADER if result["ran"] else NOT_RUN_HEADER
    review = _redact(f"{header}\n\n{result['review']}")
    (OUT_DIR / "review-output.md").write_text(review + "\n", encoding="utf-8")

    audit = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "mode": "advisory",
        "changed_files": changed_files,
        "files": audit_files,
        "anthropic_key_present": bool(_api_key()),
        "output": "/out/review-output.md",
        "exit_behavior": "always_zero_advisory",
        "reviewer": {
            "mechanism": REVIEWER_MECHANISM,
            "ran": result["ran"],
            "exit_code": result["exit_code"],
            "is_error": result["is_error"],
            "num_turns": result["num_turns"],
            "total_cost_usd": result["total_cost_usd"],
            "error": result["error"],
        },
        "mcp": mcp_audit_summary(result["invoked"]),
    }

    (OUT_DIR / "review-audit.json").write_text(
        _redact(json.dumps(audit, indent=2)),
        encoding="utf-8",
    )

    # Advisory: a critical review is still a successful run.
    return 0


def main() -> int:
    try:
        return _run()
    except Exception as exc:  # Advisory: never fail the job.
        note = (
            f"{NOT_RUN_HEADER}\n\n## Advisory Code Review\n\n"
            f"The advisory review script failed unexpectedly ({type(exc).__name__}). No review was produced.\n"
        )
        try:
            OUT_DIR.mkdir(parents=True, exist_ok=True)
            (OUT_DIR / "review-output.md").write_text(note, encoding="utf-8")
            (OUT_DIR / "review-audit.json").write_text(
                json.dumps(
                    {
                        "timestamp": datetime.now(timezone.utc).isoformat(),
                        "mode": "advisory",
                        "exit_behavior": "always_zero_advisory",
                        "reviewer": {
                            "mechanism": REVIEWER_MECHANISM,
                            "ran": False,
                            "error": type(exc).__name__,
                        },
                    },
                    indent=2,
                ),
                encoding="utf-8",
            )
        except Exception:
            pass
        return 0


if __name__ == "__main__":
    raise SystemExit(main())
